/**
 * Emit preview/page-preview.html — the whole page in the DOM the PHP render
 * callbacks produce, styled by the built bundle.css and driven by the real
 * interactions script.
 *
 * This is the cheap way to check fidelity and any stateful behaviour without a
 * WordPress install in the loop. It is only worth what its fidelity is worth, so
 * two things are non-negotiable:
 *
 *   1. Each band is wrapped in Divi's section > row > column, with Divi's own
 *      container defaults in the stand-in CSS. Otherwise a preview that looks
 *      right hides a page where the row caps every band's width.
 *   2. Divi core's `.et_pb_module { position: relative }` is reproduced. It
 *      quietly steals the containing block from anything absolutely positioned
 *      across a module boundary. A panel that a child module positions into a
 *      sibling column collapses to zero width on the real site and looks fine
 *      here without this line.
 *
 * Keep each section's markup identical to its render callback's output. When the
 * two drift, this file starts lying.
 */

const fs = require('fs');
const path = require('path');

const out = path.resolve(__dirname, '..', 'preview', 'page-preview.html');

// --- helpers ----------------------------------------------------------------

/** One module wrapper, matching ModuleTrait::module_classnames(). */
const mod = (block, inner) =>
  `<div class="${block} acme_module et_pb_module">${inner}</div>`;

const p = (...paras) => paras.map((t) => `<p>${t}</p>`).join('');

/**
 * Divi's section > row > column around one band — the same containers the
 * compiled layout puts it in.
 */
const wrap = (inner, style) => `
<section class="et_pb_section"${style ? ` style="${style}"` : ''}>
  <div class="et_pb_row">
    <div class="et_pb_column">${inner}
    </div>
  </div>
</section>`;

// --- sections ---------------------------------------------------------------
// PROJECT-SPECIFIC. One entry per band, in page order.

const parent = mod(
  'acme_parent',
  `
  <div class="acme_parent__inner">
    <span class="acme_parent__eyebrow">What we do</span>
    <h2 class="acme_parent__title">A headline lifted from the design</h2>
    <div class="acme_parent__body">${p('Body copy lifted from the design, not paraphrased.')}</div>
  </div>`
);

const children = mod(
  'acme_parent',
  `
  <div class="acme_parent__inner">
    ${[
    ['Item label', '12 projects'],
    ['Second item', '4 projects'],
  ]
    .map(([label, detail]) =>
      mod(
        'acme_child',
        `
      <div class="acme_child__row">
        <span class="acme_child__label">${label}</span>
        <span class="acme_child__detail">${detail}</span>
      </div>`
      )
    )
    .join('')}
  </div>`
);

// --- page -------------------------------------------------------------------

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Acme — module preview</title>
<link rel="stylesheet" href="../styles/bundle.css">
<style>
  body { margin: 0; background: #fff; }
  .preview-note {
    font: 13px/1.6 system-ui, sans-serif; color: #8A94A1;
    padding: 14px 40px; border-bottom: 1px solid #E3E9EF;
  }

  /* Stand-ins for Divi's containers, carrying Divi's own defaults, so the
     container reset in bundle.css is exercised here exactly as on the site. */
  .et_pb_section { padding: 5em 0; }
  .et_pb_row { width: 80%; max-width: 1080px; margin: 0 auto; }
  .et_pb_column { width: 100%; }

  /* Divi core makes every module a positioned box — see the header comment. */
  .et_pb_module {
    position: relative;
    background-size: cover;
    background-position: 50%;
    background-repeat: no-repeat;
  }
</style>
</head>
<body>
<p class="preview-note">
  Every module in the DOM its PHP render callback produces, styled by the built
  <code>styles/bundle.css</code>. Compare against the design's screens.
  <strong>Generated by tools/build-preview.js — do not edit by hand.</strong>
</p>
${wrap(parent)}
${wrap(children)}
<script src="../assets/js/acme-interactions.js"></script>
</body>
</html>
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, html, 'utf8');
console.log('Wrote', path.relative(process.cwd(), out));
